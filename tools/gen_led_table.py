#!/usr/bin/env python3
"""Generate the corrected LED table for the Sofle rev1 keymap.

Reads the keyboard's generated g_led_config (points/flags are kept verbatim) and
writes keyboards/sofle/keymaps/miryoku/led_table.h with a corrected matrix_co:
matrix cell -> LED index, as measured by walking every LED index on the board.
"""
import re

GEN = 'qmk_firmware/.build/obj_sofle_rev1_miryoku/src/default_keyboard.c'
OUT = 'keyboards/sofle/keymaps/miryoku/led_table.h'
HALF = 36                    # LEDs per half (RGB_MATRIX_LED_COUNT / 2)

gen = open(GEN).read()
start = gen.index('g_led_config = ') + len('g_led_config = ')


def take(s, i):
    """Text of the braced group starting at s[i]."""
    assert s[i] == '{', s[i:i + 10]
    depth = 0
    for j in range(i, len(s)):
        if s[j] == '{':
            depth += 1
        elif s[j] == '}':
            depth -= 1
            if depth == 0:
                return s[i:j + 1], j + 1
    raise ValueError('unbalanced braces')


whole, _ = take(gen, start)
inner = whole[1:-1].strip()
i = inner.index('{')
matrix_txt, i = take(inner, i)
i = inner.index('{', i)
points, i = take(inner, i)
i = inner.index('{', i)
flags, _ = take(inner, i)

# The physical chain of the LEFT half, recovered by walking every LED index on the
# real board (2026-10-05): indices 0-5 are the six off-grid LEDs, then the 29 key
# LEDs in this order.  The spare left thumb (4,1) reports nothing, so it did not
# appear in the walk; its LED physically sits between (4,2) and (3,3).
route = [(4, 4), (4, 3), (3, 5), (2, 5), (1, 5), (0, 5), (0, 4), (1, 4), (2, 4), (3, 4), (4, 2), (4, 1), (3, 3),
         (2, 3), (1, 3), (0, 3), (0, 2), (1, 2), (2, 2), (3, 2), (4, 0), (3, 1), (2, 1), (1, 1), (0, 1), (0, 0),
         (1, 0), (2, 0), (3, 0)]
assert len(route) == 29

idx = {}
for k, (r, c) in enumerate(route):
    idx[(r, c)] = 6 + k            # left half: 0-5 off-grid, then the keys
    idx[(r + 5, c)] = 36 + 6 + k   # right half: same relative order, +36 (mirrored)

OFF_GRID = [0, 1, 2, 3, 4, 5, HALF - 1]      # knob LED + six underglow, plus one last
# Static pattern, per half, in the half's own cell numbering (so the same cells are
# used for both halves and the split driver drops the half that does not own them):
#   outer column rows 1-3 + the outer thumb, inner column rows 1-3, the four inner thumbs
ACCENT_CELLS = [(1, 0), (2, 0), (3, 0), (4, 0), (1, 5), (2, 5), (3, 5), (4, 1), (4, 2), (4, 3), (4, 4)]

accents = []
for base in (0, HALF):
    accents += [base + o for o in OFF_GRID if o != 0]                     # off-grid ring (0 is the dim knob LED)
    accents += [idx[(r + (5 if base else 0), c)] for (r, c) in ACCENT_CELLS]  # already global
assert len(accents) == 34, len(accents)

accent_lines = []
per_half = len(accents) // 2
for i in range(0, len(accents), 6):
    tag = ''
    if i == 0:
        tag = '    // left half: off-grid ring, outer column, inner column, thumbs\n'
    elif i == per_half:
        tag = '    // right half (same cells, other strip)\n'
    accent_lines.append(tag + '    ' + ', '.join('%2d' % v for v in accents[i:i + 6]) + ',')

rows = []
for r in range(10):
    row = []
    for c in range(6):
        if (r, c) in idx:
            row.append(idx[(r, c)])
        else:
            assert r in (4, 9) and c == 5, (r, c)   # only the two knob cells have no LED
            row.append('NO_LED')
    rows.append(row)

lines = []
for row in rows:
    lines.append('        { ' + ', '.join(('%3d' % v) if isinstance(v, int) else v.rjust(6) for v in row) + ' },')

out = f'''// Generated by tools/gen_led_table.py - do not hand-edit; re-run that instead.
//
// == Corrected LED table ==
//
// The keyboard definition (keyboards/sofle/rev1/keyboard.json + sofle/info.json)
// calls out the wrong LED ORDER in its `matrix_co` table: the physical chain of
// each half does not follow the column serpentine it describes, so pressing a key
// lit a different key's LED (the wide left thumb lit `Y`, the wide right thumb lit
// the key below/right of `L`, and some keys lit an under-the-case LED far away).
//
// Measured 2026-10-05 by walking every LED index on the real board - both halves
// flashed with a temporary build that lit one index at a time and printed it on
// the OLED, then pressing the key under the lit LED (see AGENTS.md, "LED table").
// Result: indices 0-5 of each half are the six off-grid LEDs (underglow + the knob
// LED), the 29 key LEDs then follow the route below, and the last LED of the half
// is off-grid again.  The two knob LEDs (json flags: 8) are indices 0 and 36, which
// is why this keymap paints exactly those two dimly.
//
// Only `matrix_co` (matrix cell -> LED index) is corrected - that is what the
// keypress-reactive effect and any other hit-driven path uses.  `point[]` and
// `flags[]` are the keyboard's own, unchanged; they only affect position-based
// effects, which this keymap does not enable.
//
// The generated definition is weak, so this strong one wins.
led_config_t g_led_config = {{
    // matrix cell -> LED index
    {{
{chr(10).join(lines)}
    }},
    // LED index -> physical position (keyboard default)
    {points},
    // LED index -> flags (keyboard default)
    {flags},
}};

// == Static accent pattern ==
// The LEDs below are painted a calm blue by rgb_matrix_indicators_advanced_user()
// unless the reactive effect has a live hit on them, so a keypress pulse still
// shows through.  Derived from the table above: the off-grid ring of each half
// (underglow; index 0 / 36 is the knob LED and is painted dimmer separately), plus
// per half the outer column, the inner column and the thumbs.
static const uint8_t led_accents[] = {{
{chr(10).join(accent_lines)}
}};
'''

open(OUT, 'w').write(out)
print('wrote', OUT, len(out), 'bytes')
print('left thumb row:', [idx.get((4, c), 'NO_LED') for c in range(6)])
print('right thumb row:', [idx.get((9, c), 'NO_LED') for c in range(6)])
print('cross-check  cell (3,1) ->', idx[(3, 1)], ' (walk+json both say 27)')
print('cross-check  cell (8,1) ->', idx[(8, 1)], ' (walk+json both say 63)')
